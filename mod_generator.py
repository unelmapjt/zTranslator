"""
zTranzlator - Multi-Archetype Mod Patch Generator (Phase 2)
Type A (Translate/JP JSON), Type B (printMedia txt), Type C (Non-destructive Lua Hooks)
およびハイブリッド構成に対応した独立日本語化MOD (〇〇_JA) の自動生成モジュール。
"""

