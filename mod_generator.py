HOOK_LUA_TEMPLATE = """--[[
    zTranzlator Non-Destructive Translation Patch
    Target Mod: {mod_name} ({mod_id})
    Mode: Native Translate/JP/UI.json Interceptor (The Ark Style)
    Note: 100% pure ASCII to prevent any charset encoding issues.
--]]

local MOD_ID = "{mod_id}_JA"
local PREFIX = "UI_{mod_id}_"

zTranzlatorSettings = zTranzlatorSettings or {{}}
zTranzlatorSettings["{mod_id}"] = true

local function isEnabled()
    return zTranzlatorSettings["{mod_id}"] == true
end

local _orig_getText = getText
if _orig_getText then
    getText = function(key, ...)
        if isEnabled() and key and type(key) == "string" then
            local transKey = PREFIX .. key
            local val = _orig_getText(transKey, ...)
            if val and val ~= transKey then
                return val
            end
        end
        return _orig_getText(key, ...)
    end
end

if Translator and Translator.getText then
    local _orig_trans_getText = Translator.getText
    Translator.getText = function(key, ...)
        if isEnabled() and key and type(key) == "string" then
            local transKey = PREFIX .. key
            local val = _orig_trans_getText(transKey, ...)
            if val and val ~= transKey then
                return val
            end
        end
        return _orig_trans_getText(key, ...)
    end
end

local function hookDirect()
    if Viewpoint then
        if Viewpoint.Keys and Viewpoint.Keys.label then
            local orig_label = Viewpoint.Keys.label
            Viewpoint.Keys.label = function(id)
                local orig = orig_label(id)
                if orig and getText then return getText(orig) end
                return orig
            end
        end
        if Viewpoint.Keys and Viewpoint.Keys.group then
            local orig_group = Viewpoint.Keys.group
            Viewpoint.Keys.group = function(id)
                local orig = orig_group(id)
                if orig and getText then return getText(orig) end
                return orig
            end
        end
        if Viewpoint.Pads and Viewpoint.Pads.label then
            local orig_pad_label = Viewpoint.Pads.label
            Viewpoint.Pads.label = function(id)
                local orig = orig_pad_label(id)
                if orig and getText then return getText(orig) end
                return orig
            end
        end
    end
end

hookDirect()
Events.OnGameBoot.Add(hookDirect)
Events.OnMainMenuEnter.Add(hookDirect)
"""


def generate_poster_image(file_path: Path, title: str):
    """MOD用の256x256高品質ポスター画像を生成 (Pillow使用、非破壊フォールバック付き)"""
    try:
        from PIL import Image, ImageDraw, ImageFont

        # 256x256 のダーク調背景作成 (Project Zomboidスタイル)
        img = Image.new("RGBA", (256, 256), (18, 20, 24, 255))
        draw = ImageDraw.Draw(img)

        # 背景グラデーション風ストライプ
        for y in range(0, 256, 4):
            alpha = int(15 + (y / 256.0) * 35)
            draw.line([(0, y), (256, y)], fill=(32, 40, 52, alpha))

        # 赤いアクセントフレーム (Zomboidの警告カラー)
        draw.rectangle([(6, 6), (249, 249)], outline=(180, 40, 40, 200), width=2)
        draw.rectangle([(10, 10), (245, 245)], outline=(60, 70, 80, 150), width=1)

        # フォント取得
        font_large = None
        font_small = None
        for font_candidate in [
            "C:/Windows/Fonts/meiryo.ttc",
            "C:/Windows/Fonts/msgothic.ttc",
            "C:/Windows/Fonts/segoeuib.ttf",
            "C:/Windows/Fonts/arialbd.ttf"
        ]:
            if Path(font_candidate).is_file():
                try:
                    font_large = ImageFont.truetype(font_candidate, 20)
                    font_sub = ImageFont.truetype(font_candidate, 16)
                    font_small = ImageFont.truetype(font_candidate, 12)
                    break
                except Exception:
                    continue

        if not font_large:
            font_large = font_sub = font_small = ImageFont.load_default()

        # タイトル描画
        display_title = title if len(title) <= 18 else title[:16] + ".."
        draw.text((128, 70), display_title, font=font_large, fill=(240, 240, 240), anchor="mm")

        # バッジ背景
        draw.rounded_rectangle([(38, 115), (218, 148)], radius=6, fill=(160, 32, 32, 230))
        draw.text((128, 131), "日本語化パッチ", font=font_sub, fill=(255, 255, 255), anchor="mm")

        # 付属情報
        draw.text((128, 180), "Build 42 Ready", font=font_small, fill=(180, 190, 200), anchor="mm")
        draw.text((128, 225), "Generated by zTranzlator", font=font_small, fill=(110, 120, 130), anchor="mm")

        img.save(file_path, "PNG")
        print(f"  [+] ポスター画像作成完了 -> {file_path.name} (256x256)")
        return
    except Exception as e:
        print(f"  [Warn] 高画質ポスター生成フォールバック: {e}")

    # フォールバック (最小1x1 PNG)
    png_bytes = bytes([
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
        0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
        0x0D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x60, 0x60, 0x60, 0x60,
        0x00, 0x00, 0x00, 0x05, 0x00, 0x01, 0xa7, 0x24, 0x55, 0xc4, 0x00, 0x00,
        0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82
    ])
    try:
        with open(file_path, "wb") as f:
            f.write(png_bytes)
    except Exception:
        pass


def generate_patch_mod(mod_id: str, mod_name: str, translated_items: List[Dict[str, Any]], output_dir: Path, target_lang: str = "JP"):
    """
    全アーキテクチャ統合型MODパッチジェネレーター。
    """
    from i18n import SUPPORTED_TARGET_LANGUAGES
    meta = SUPPORTED_TARGET_LANGUAGES.get(target_lang, {"name": target_lang, "en_name": target_lang, "suffix": f"_{target_lang}"})
    suffix = meta.get("suffix", f"_{target_lang}")
    lang_name = meta.get("name", target_lang)

    patch_dir = output_dir / f"{mod_id}{suffix}"
    patch_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n============================================================")
    print(f"[ジェネレーター] MODパッチを生成中: {mod_name} ({mod_id}) -> {lang_name}")
    print(f"                 出力先: {patch_dir}")
    print(f"============================================================")

    # 1. mod.info の生成
    mod_info_content = f"""name={mod_name} [{lang_name}] (zTranzlator)
id={mod_id}{suffix}
require={mod_id}
description={mod_name} translation patch ({lang_name}). (Generated by zTranzlator by Uni-SJ | Build 42 Ready)
poster=poster.png
versionMin=42.0.0
author=Uni-SJ (Tool: zTranzlator)
url=https://steamcommunity.com/profiles/76561198062851438/myworkshopfiles?appid=108600
"""
    with open(patch_dir / "mod.info", "w", encoding="utf-8") as f:
        f.write(mod_info_content)
    
    # B42 common/ にも mod.info を配置 (B42最新ワークショップ互換)
    common_dir = patch_dir / "common"
    common_dir.mkdir(parents=True, exist_ok=True)
    with open(common_dir / "mod.info", "w", encoding="utf-8") as f:
        f.write(mod_info_content)

    print(f"  [+] mod.info 生成完了 (require={mod_id}, versionMin=42.0.0)")

    # ワークショップ投稿用説明文テンプレート (そのままコピーしてSteam投稿可能)
    workshop_desc = f"""[h1]{mod_name} 日本語化パッチ (Build 42)[/h1]
★🔤English description is below🔤★

[h2][Japanese Description][/h2]
「{mod_name}」を完全非破壊で日本語化するパッチMODです。
元MODの本体ファイルを一切書き換えず、独立した連動パッチMOD（require={mod_id}）として動作します。

[h2]■ 主な特徴[/h2]
[list]
[*] [b]完全非破壊パッチ:[/b] 元MODの更新時でもデータが破損せず、差分を自動継承します。
[*] [b]ゲーム内トグル対応:[/b] ModOptions設定からいつでも日本語と英語を切り替え可能。
[*] [b]UI文字幅最適化:[/b] ボタン枠やウィンドウ枠からはみ出さないよう配慮した日本語表記。
[/list]

[h2]■ 必須MOD / ロード順[/h2]
[list]
[*] 元MOD「{mod_name}」が必須です。
[*] ロード順は必ず元MODよりも後（下）に設定してください。
[/list]

[h2]■ クレジット ＆ ライセンス表記[/h2]
[list]
[*] [b]元MOD製作者様:[/b] 素晴らしいMODの開発に心より感謝申し上げます。
[*] [b]日本語化ツール:[/b] [url=https://steamcommunity.com/profiles/76561198062851438/myworkshopfiles?appid=108600]zTranzlator by Uni-SJ[/url]
[/list]
※本パッチは元MODの著作権を尊重し、元ファイルを再配布しない非破壊パッチ形式を採用しています。

-----------------------------------------------------------
[h2][English Description][/h2]
[h1]{mod_name} Japanese Translation Patch (Build 42)[/h1]
A zero-destruction Japanese translation patch for "{mod_name}".
Operates as an independent companion mod (require={mod_id}) without altering the original files.

[h2]■ Requirements[/h2]
[list]
[*] Base mod "{mod_name}" is strictly required.
[*] Ensure this patch is loaded AFTER the base mod.
[/list]

[h2]■ Credits & License[/h2]
[list]
[*] [b]Original Mod Author:[/b] All credits and copyrights belong to the original mod author.
[*] [b]Translation Tool:[/b] [url=https://steamcommunity.com/profiles/76561198062851438/myworkshopfiles?appid=108600]zTranzlator by Uni-SJ[/url]
[/list]
"""
    with open(patch_dir / "WORKSHOP_DESCRIPTION.txt", "w", encoding="utf-8") as f:
        f.write(workshop_desc)

    # ライセンスおよび再配布に関する注意事項
    readme_license = f"""============================================================
{mod_name} 日本語化パッチ (zTranzlator Generated)
============================================================

【公開・再配布に関するライセンスおよび注意事項】

1. 元MODの権利尊重
   本パッチは「{mod_name}」のオリジナル制作者様の著作権および利用規約を
   最大限尊重し、元MODのファイルを1文字も改変・再配布しない
   「独立パッチ（require={mod_id}）」方式を採用しています。

2. ワークショップ公開時の表記お願い
   本パッチをSteamワークショップやコミュニティ等で公開・共有される場合は、
   同封の「WORKSHOP_DESCRIPTION.txt」を参考に、
   ・元MODへのリンクとクレジット
   ・日本語化ツール「zTranzlator (Author: Uni-SJ)」のクレジット表記
     (URL: https://steamcommunity.com/profiles/76561198062851438/myworkshopfiles?appid=108600 )
   を記載してください。

3. 免責事項
   元MODのアップデート等によりテキストの変更や構造変化が生じた場合は、
   zTranzlator を用いて差分再スキャン・更新を行ってください。

Generated with zTranzlator Build 42 Translation Suite
Author: Uni-SJ
============================================================
"""
    with open(patch_dir / "README_LICENSE.txt", "w", encoding="utf-8") as f:
        f.write(readme_license)

    print(f"  [+] WORKSHOP_DESCRIPTION.txt & README_LICENSE.txt 生成完了")

    # ポスター画像の配置
    poster_path = patch_dir / "poster.png"
    if not poster_path.is_file():
        generate_poster_image(poster_path, mod_name)

    # アイテムをアーキテクチャ別に仕分け
    type_a_files = {}       # { "UI.json": { key: jp }, ... }
    type_b_files = {}       # { "doc1.txt": jp_content, ... }
    type_c_dict = {}        # { en_text: jp_text }

    from mod_scanner import is_meaningful_translation

    for item in translated_items:
        en = item.get("en", "")
        jp = item.get("jp", "")
        file_type = item.get("file_type", "")
        rel_path = item.get("rel_path", "")
        key = item.get("key", "")

        if not jp or not is_meaningful_translation(en, jp):
            continue

        if file_type in ("json", "txt") and rel_path and ("Translate" in rel_path or key):
            # Type A: 公式Translate系
            # 出力先ファイル名を決定 (例: UI_EN.txt -> UI.json, ItemName.json -> ItemName.json)
            p = Path(rel_path)
            stem = p.stem
            if stem.endswith("_EN"):
                stem = stem[:-3]
            target_json_name = f"{stem}.json"

            if target_json_name not in type_a_files:
                type_a_files[target_json_name] = {}
            target_keys = item.get("keys", [])
            if not target_keys:
                target_keys = [key] if key else [en]
            for tk in target_keys:
                type_a_files[target_json_name][tk] = jp

        elif file_type == "printMedia" or "printMedia" in rel_path:
            # Type B: メディアテキスト (The Ark等) - 元MODの相対フォルダ構造を忠実に再現
            rel = Path(rel_path) if rel_path else Path(item.get("file", "document.txt"))
            parts = list(rel.parts)
            if parts and parts[0] in ("42", "common", "42.0", "42.15", "42.18"):
                parts = parts[1:]
            if parts and parts[0] == "media":
                parts = parts[1:]
            sub_path_str = str(Path(*parts)) if parts else f"textures/printMedia/txt/{rel.name}"
            type_b_files[sub_path_str] = jp

        else:
            # Type C: ハードコードLua / JAR / 不明
            type_c_dict[en] = jp

    # 2. Type A: Translate/<target_lang>/*.json の出力 (Build 42 全バージョン & レガシー完全互換)
    if type_a_files:
        langs_to_write = [target_lang]
        if target_lang == "JP" and "JA" not in langs_to_write:
            langs_to_write.append("JA")
        elif target_lang == "JA" and "JP" not in langs_to_write:
            langs_to_write.append("JP")

        # B42の全サブバージョン (42, common, 42.0, 42.15, 42.18, および ルート直下) にパッチ配置
        sub_bases = ["42", "common", "42.0", "42.15", "42.18", ""]
        for lang in langs_to_write:
            for sub_base in sub_bases:
                if sub_base:
                    translate_target_dir = patch_dir / sub_base / "media" / "lua" / "shared" / "Translate" / lang
                else:
                    translate_target_dir = patch_dir / "media" / "lua" / "shared" / "Translate" / lang
                translate_target_dir.mkdir(parents=True, exist_ok=True)

                for json_filename, entries in type_a_files.items():
                    # JSON出力 (B42標準)
                    out_json = translate_target_dir / json_filename
                    with open(out_json, "w", encoding="utf-8") as f:
                        json.dump(entries, f, ensure_ascii=False, indent=2)

                    # レガシーTXT (*_JA.txt / *_JP.txt) も同時生成 (ゲーム本体の旧バージョン・独自ローダー対応)
                    txt_stem = Path(json_filename).stem
                    out_txt = translate_target_dir / f"{txt_stem}_{lang}.txt"
                    try:
                        with open(out_txt, "w", encoding="utf-8") as tf:
                            tf.write(f"{txt_stem}_{lang} = {{\n")
                            for ek, ev in entries.items():
                                safe_v = ev.replace('"', '\\"').replace("\n", "\\n")
                                tf.write(f'    {ek} = "{safe_v}",\n')
                            tf.write("}\n")
                    except Exception:
                        pass
            print(f"  [+] Type A (公式JSON & TXT) 出力: Translate/{lang} ({len(type_a_files)} ファイル, 全バージョン階層対応)")

    # 3. Type B: printMedia 等のメディアテキスト出力 (元MODの階層構造を完全継承)
    if type_b_files:
        for sub_path_str, content in type_b_files.items():
            for sub_base in ("42", "common"):
                out_txt = patch_dir / sub_base / "media" / sub_path_str
                out_txt.parent.mkdir(parents=True, exist_ok=True)
                with open(out_txt, "w", encoding="utf-8") as f:
                    f.write(content)
            print(f"  [+] Type B (メディア文書) 出力: media/{sub_path_str}")

    # 4. Type C: 非破壊Luaフック & 辞書の出力
    if type_c_dict:
        lua_client_dir = patch_dir / "42" / "media" / "lua" / "client"
        lua_client_dir.mkdir(parents=True, exist_ok=True)

        # Lua辞書テーブル文字列
        lua_entries = []
        for en, jp in sorted(type_c_dict.items()):
            safe_en = en.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            safe_jp = jp.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lua_entries.append(f'    ["{safe_en}"] = "{safe_jp}",')
        dict_lua_table = "{\n" + "\n".join(lua_entries) + "\n}"

        hook_lua = HOOK_LUA_TEMPLATE.format(
            mod_name=mod_name,
            mod_id=mod_id,
            dict_lua_table=dict_lua_table
        )
        # 1. UTF-8 TSV 辞書ファイルの出力 (getModFileReader による文字化けゼロ読み込み用)
        dict_txt_file = lua_client_dir / f"zTranz_Dict_{mod_id}.txt"
        with open(dict_txt_file, "w", encoding="utf-8") as f:
            for en, jp in sorted(type_c_dict.items()):
                f.write(f"{en}\t{jp}\n")
        print(f"  [+] UTF-8 辞書ファイル出力: media/lua/client/{dict_txt_file.name}")

        # 2. Lua フック本体の出力 (Windows-31J 環境の文字化けを防ぐため CP932 を優先)
        hook_file = lua_client_dir / f"zTranz_Hook_{mod_id}.lua"
        try:
            with open(hook_file, "w", encoding="cp932") as f:
                f.write(hook_lua)
        except UnicodeEncodeError:
            with open(hook_file, "w", encoding="utf-8") as f:
                f.write(hook_lua)
        print(f"  [+] Type C (Luaフック) 出力: media/lua/client/{hook_file.name} ({len(type_c_dict)} 語)")

        # 同梱辞書JSON (バックアップ・外部ツール参照用)
        with open(lua_client_dir / f"zTranz_Dict_{mod_id}.json", "w", encoding="utf-8") as f:
            json.dump(type_c_dict, f, ensure_ascii=False, indent=2)

        # Type C を The Ark 方式 (Translate/JP/UI.json) と完全連携
        # PZのTranslator.getTextは "UI_" で始まるキーのみをUTF-8辞書から引く仕様のため、
        # 接頭辞付きキーを UI.json に登録し、Lua側からは純粋ASCIIでこれを呼び出す
        ui_json_entries = {}
        for en, jp in type_c_dict.items():
            ui_json_entries[f"UI_{mod_id}_{en}"] = jp
            ui_json_entries[f"UI_optionscreen_binding_{en}"] = jp
            ui_json_entries[en] = jp

        for lang in ("JP", "JA"):
            tr_dir = patch_dir / "42" / "media" / "lua" / "shared" / "Translate" / lang
            tr_dir.mkdir(parents=True, exist_ok=True)
            with open(tr_dir / "UI.json", "w", encoding="utf-8") as f:
                json.dump(ui_json_entries, f, ensure_ascii=False, indent=2)
            # common側にも展開
            common_tr_dir = patch_dir / "common" / "media" / "lua" / "shared" / "Translate" / lang
            common_tr_dir.mkdir(parents=True, exist_ok=True)
            with open(common_tr_dir / "UI.json", "w", encoding="utf-8") as f:
                json.dump(ui_json_entries, f, ensure_ascii=False, indent=2)

    # 5. Build 42 / 従来ローダー両対応のため ルート直下にも media/ をミラー
    src_42_media = patch_dir / "42" / "media"
    root_media = patch_dir / "media"
    if src_42_media.is_dir():
        if root_media.exists():
            shutil.rmtree(root_media)
        shutil.copytree(src_42_media, root_media)
        print(f"  [+] ルート直下 media/ ミラー同期完了")

    print(f"\n[生成完了] {mod_name}_JA パッチMODのビルドに成功しました！\n")
    return patch_dir
